test_that("mesa_spectrum matches stats::ar.burg and finds the cycles", {
  set.seed(1)
  t <- seq(0, 600, by = 2)
  y <- sin(2 * pi * t / 100) + 0.6 * sin(2 * pi * t / 41) + rnorm(length(t), sd = 0.5)
  m <- mesa_spectrum(data.frame(t, y), order = 12)
  a <- stats::ar.burg(y - mean(y), aic = FALSE, order.max = 12)
  expect_equal(m$ar, as.numeric(a$ar), tolerance = 1e-8)
  expect_equal(m$noise_variance, a$var.pred, tolerance = 1e-8)
  m2 <- mesa_spectrum(data.frame(t, y))
  expect_s3_class(m2, "mesa_spectrum")
  expect_true(any(abs(m2$peaks$period - 100) < 5))
  expect_true(any(abs(m2$peaks$period - 41) < 3))
  expect_equal(nrow(m2$spectrum), 2048)
  expect_true(all(m2$spectrum$power > 0))
  expect_error(mesa_spectrum(data.frame(1:5, 1:5)))
  tu <- t[-51] + 0.5 * (seq_len(300) %% 2)
  expect_message(mesa_spectrum(data.frame(tu, y[-51])), "unevenly")
  png(tempfile())
  on.exit(dev.off())
  expect_silent(plot_mesa_spectrum(m2))
})

test_that("test_tuned recovers a known precession constant", {
  set.seed(1)
  k <- 21
  fr <- c(-18.85, -26.348, 4.257452, 7.452, 17.916)
  amp <- c(1, 0.3, 1, 0.87, 0.7)
  t <- 0:4000
  P <- 1296 / (1296 / k + fr)
  x <- numeric(length(t))
  for (i in 1:5) {
    x <- x + amp[i] * cos(2 * pi * t / P[i] + runif(1, 0, 2 * pi))
  }
  x <- x +
      0.8 * cos(2 * pi * t / 405) + 1.5 * as.numeric(stats::arima.sim(list(ar = 0.7), length(t)))
  out <- utils::capture.output(r <- test_tuned(data.frame(t, x), tbw = 2, n_surr = 2, plot = FALSE))
  expect_true(abs(r$k[["k"]] - k) < 0.3)
  expect_true(grepl("^PASS", r$k_status))
  out2 <- utils::capture.output(test_tuned_check(k_true = 21.2, len = 4000))
  expect_true(any(grepl("true k 21.20", out2)))
})

test_that("evolutive MESA spans the record, pads, and tracks a changing cycle", {
  set.seed(2)
  t <- seq(0, 800, by = 2)
  y <- sin(2 * pi * cumsum(1 / ifelse(t < 400, 40, 80)) * 2) + rnorm(length(t), sd = 0.4)
  d <- data.frame(t, y)
  ev <- mesa_evolutive(d, window = c(100, 200), order = 20)
  expect_s3_class(ev, "mesa_evolutive")
  expect_equal(length(ev$windows), 2)
  expect_equal(range(ev$position), c(0, 800))
  expect_false(anyNA(ev$windows[[1]]$power))
  evn <- mesa_evolutive(d, window = 200, order = 20, pad = "none")
  expect_true(anyNA(evn$windows[[1]]$power) || ncol(evn$windows[[1]]$power) == length(evn$position))
  tr <- track_mesa(ev, window = 200, period = c(25, 120))
  expect_s3_class(tr, "mesa_track")
  expect_true(median(tr$period[tr$position < 300]) < 50)
  expect_true(median(tr$period[tr$position > 500]) > 60)
  av <- mesa_average(ev, 1)
  expect_equal(nrow(av), length(ev$frequency))
  png(tempfile())
  on.exit(dev.off())
  expect_silent(plot_mesa_evolutive(ev, average = TRUE, track = tr, peaks = TRUE))
  expect_silent(plot_mesa_evolutive(ev, vertical = FALSE, xaxis = "frequency"))
  s <- mesa_spectrum(d, window = c(-100, 100), order = 10)
  expect_equal(s$window, c(-100, 100))
  expect_error(track_mesa(ev, window = 200))
})
